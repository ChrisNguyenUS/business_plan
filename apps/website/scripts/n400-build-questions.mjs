#!/usr/bin/env node
// Parses ../docs/N400_questions_{en,vi}.md into a typed TS module.
// Runs offline; output committed to src/lib/n400/questions-data.ts.

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '../../..');
const EN_PATH = resolve(ROOT, 'docs/learning_type/civic_questions/N400_questions_en.md');
const VI_PATH = resolve(ROOT, 'docs/learning_type/civic_questions/N400_questions_vi.md');
const OUT_PATH = resolve(__dirname, '../src/lib/n400/questions-data.ts');

const LOCATION_BASED_IDS = new Set([23, 29, 61, 62]);

const CATEGORY_KEYS = {
  'Principles of American Democracy': 'principles',
  'System of Government': 'system',
  'Rights and Responsibilities': 'rights',
  'American History': 'history',
  'Symbols and Holidays': 'symbols',
};

const CATEGORY_VI = {
  principles: 'Nguyên Tắc Dân Chủ',
  system: 'Hệ Thống Chính Phủ',
  rights: 'Quyền & Trách Nhiệm',
  history: 'Lịch Sử Mỹ',
  symbols: 'Biểu Tượng & Ngày Lễ',
};

function parseLang(markdown) {
  const result = new Map();
  let currentCategoryEn = '';
  let currentId = null;
  let currentQuestion = '';
  let currentAnswers = [];

  const flush = () => {
    if (currentId !== null) {
      result.set(currentId, {
        category: currentCategoryEn,
        question: currentQuestion,
        answers: currentAnswers,
      });
    }
  };

  for (const raw of markdown.split('\n')) {
    const line = raw.trim();

    // Match category headers in EN: "## PART A: Principles of American Democracy"
    const catEn = line.match(/^##\s+PART\s+\w+:\s+(.+)$/);
    if (catEn) {
      currentCategoryEn = catEn[1].trim();
      continue;
    }

    // Match category headers in VI: "## PHẦN A: Các Nguyên Tắc Dân Chủ Hoa Kỳ"
    const catVi = line.match(/^##\s+PHẦN\s+\w+:\s+(.+)$/);
    if (catVi) {
      // VI markdown: keep VI category text (different from EN). We tag via id mapping later.
      currentCategoryEn = catVi[1].trim();
      continue;
    }

    const q = line.match(/^\*\*(\d+)\.\s+(.+?)\*\*$/);
    if (q) {
      flush();
      currentId = parseInt(q[1], 10);
      currentQuestion = q[2].trim();
      currentAnswers = [];
      continue;
    }

    const ans = line.match(/^\*\s+(.+)$/);
    if (ans && currentId !== null) {
      currentAnswers.push(ans[1].trim());
    }
  }
  flush();
  return result;
}

function categoryKey(enCategory) {
  for (const [name, key] of Object.entries(CATEGORY_KEYS)) {
    if (enCategory === name) return key;
  }
  throw new Error(`Unknown category: ${enCategory}`);
}

function jsonString(s) {
  return JSON.stringify(s);
}

function main() {
  const enMd = readFileSync(EN_PATH, 'utf-8');
  const viMd = readFileSync(VI_PATH, 'utf-8');

  const enMap = parseLang(enMd);
  const viMap = parseLang(viMd);

  if (enMap.size !== 128) {
    console.error(`EN: expected 128 questions, got ${enMap.size}`);
    process.exit(1);
  }
  if (viMap.size !== 128) {
    console.error(`VI: expected 128 questions, got ${viMap.size}`);
    process.exit(1);
  }

  const records = [];
  for (let id = 1; id <= 128; id++) {
    const en = enMap.get(id);
    const vi = viMap.get(id);
    if (!en) throw new Error(`Missing EN Q${id}`);
    if (!vi) throw new Error(`Missing VI Q${id}`);

    const cat = categoryKey(en.category);
    const isLocationBased = LOCATION_BASED_IDS.has(id);

    records.push({
      id,
      category: cat,
      questionEn: en.question,
      questionVi: vi.question,
      answersEn: en.answers,
      answersVi: vi.answers,
      isLocationBased,
    });
  }

  const lines = [];
  lines.push('// AUTO-GENERATED by scripts/n400-build-questions.mjs — do not edit by hand.');
  lines.push('// Source: docs/N400_questions_en.md + docs/N400_questions_vi.md');
  lines.push('');
  lines.push("export type N400CategoryKey = 'principles' | 'system' | 'rights' | 'history' | 'symbols';");
  lines.push('');
  lines.push('export interface N400Question {');
  lines.push('  id: number;');
  lines.push('  category: N400CategoryKey;');
  lines.push('  questionEn: string;');
  lines.push('  questionVi: string;');
  lines.push('  answersEn: string[];');
  lines.push('  answersVi: string[];');
  lines.push('  isLocationBased: boolean;');
  lines.push('}');
  lines.push('');
  lines.push('export const N400_CATEGORY_LABELS: Record<N400CategoryKey, { en: string; vi: string }> = {');
  for (const [name, key] of Object.entries(CATEGORY_KEYS)) {
    lines.push(`  ${key}: { en: ${jsonString(name)}, vi: ${jsonString(CATEGORY_VI[key])} },`);
  }
  lines.push('};');
  lines.push('');
  lines.push('export const N400_QUESTIONS: N400Question[] = [');
  for (const r of records) {
    lines.push('  {');
    lines.push(`    id: ${r.id},`);
    lines.push(`    category: ${jsonString(r.category)},`);
    lines.push(`    questionEn: ${jsonString(r.questionEn)},`);
    lines.push(`    questionVi: ${jsonString(r.questionVi)},`);
    lines.push(`    answersEn: ${JSON.stringify(r.answersEn)},`);
    lines.push(`    answersVi: ${JSON.stringify(r.answersVi)},`);
    lines.push(`    isLocationBased: ${r.isLocationBased},`);
    lines.push('  },');
  }
  lines.push('];');
  lines.push('');
  lines.push('export const N400_QUESTIONS_BY_ID: Map<number, N400Question> = new Map(');
  lines.push('  N400_QUESTIONS.map((q) => [q.id, q])');
  lines.push(');');
  lines.push('');

  writeFileSync(OUT_PATH, lines.join('\n'), 'utf-8');
  console.log(`Wrote ${records.length} questions to ${OUT_PATH}`);
}

main();
