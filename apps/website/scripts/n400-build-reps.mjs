#!/usr/bin/env node
// Parses scripts/n400/reps-2025.csv into a typed TS module keyed by (state, district).
// Output committed to src/lib/n400/reps-data.ts. Re-run after updating the CSV.

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const CSV_PATH = resolve(__dirname, 'n400/reps-2025.csv');
const OUT_PATH = resolve(__dirname, '../src/lib/n400/reps-data.ts');

function parseCsv(text) {
  const lines = text.split('\n').filter((l) => l.trim().length > 0);
  const [, ...rows] = lines; // skip header
  return rows.map((line) => {
    // Simple split — none of our fields contain commas. Audio URLs have spaces, %20, etc.
    const [state_code, district_number, rep_name, rep_audio_url] = line.split(',');
    return {
      state_code: state_code.trim(),
      district_number: parseInt(district_number, 10),
      rep_name: rep_name.trim(),
      rep_audio_url: rep_audio_url.trim(),
    };
  });
}

function jsonString(s) {
  return JSON.stringify(s);
}

function main() {
  const csv = readFileSync(CSV_PATH, 'utf-8');
  const reps = parseCsv(csv);

  // Group by state for inspection / sanity, but emit a flat lookup map.
  const lines = [];
  lines.push('// AUTO-GENERATED by scripts/n400-build-reps.mjs — do not edit by hand.');
  lines.push('// Source: scripts/n400/reps-2025.csv');
  lines.push('');
  lines.push("import type { StateCode } from './state-data';");
  lines.push('');
  lines.push('export interface RepInfo {');
  lines.push('  stateCode: StateCode;');
  lines.push('  districtNumber: number;');
  lines.push('  name: string;');
  lines.push('  audioUrl: string;');
  lines.push('}');
  lines.push('');
  lines.push('export const REPS: RepInfo[] = [');
  for (const r of reps) {
    lines.push(
      `  { stateCode: ${jsonString(r.state_code)} as StateCode, districtNumber: ${r.district_number}, name: ${jsonString(r.rep_name)}, audioUrl: ${jsonString(r.rep_audio_url)} },`
    );
  }
  lines.push('];');
  lines.push('');
  lines.push('// Keyed lookup: `${stateCode}-${districtNumber}` → RepInfo');
  lines.push('export const REPS_BY_KEY: Map<string, RepInfo> = new Map(');
  lines.push("  REPS.map((r) => [`${r.stateCode}-${r.districtNumber}`, r])");
  lines.push(');');
  lines.push('');
  lines.push('// State-grouped lookup: stateCode → RepInfo[] (sorted by district)');
  lines.push('export const REPS_BY_STATE: Map<StateCode, RepInfo[]> = (() => {');
  lines.push('  const m = new Map<StateCode, RepInfo[]>();');
  lines.push('  for (const r of REPS) {');
  lines.push('    const arr = m.get(r.stateCode) ?? [];');
  lines.push('    arr.push(r);');
  lines.push('    m.set(r.stateCode, arr);');
  lines.push('  }');
  lines.push('  for (const arr of m.values()) arr.sort((a, b) => a.districtNumber - b.districtNumber);');
  lines.push('  return m;');
  lines.push('})();');
  lines.push('');
  lines.push('export function repForDistrict(stateCode: StateCode, districtNumber: number | null): RepInfo | null {');
  lines.push('  if (districtNumber === null) return null;');
  lines.push('  return REPS_BY_KEY.get(`${stateCode}-${districtNumber}`) ?? null;');
  lines.push('}');
  lines.push('');

  writeFileSync(OUT_PATH, lines.join('\n'), 'utf-8');
  console.log(`Wrote ${reps.length} reps to ${OUT_PATH}`);
}

main();
